// Run the actual browser calculator in isolation, with no DOM or package dependencies.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../src/app.js'), 'utf8');
const start = source.indexOf('  function aciCalc(');
const end = source.indexOf('  const meRow', start);
assert(start >= 0 && end > start, 'calculator function remains available for isolated checks');
const context = { Number, Math };
vm.createContext(context);
vm.runInContext(source.slice(start, end), context);
const calculate = context.aciCalc;
const stages = [{ st: '1', w: 50, hr: 108, vo2: 1.15 }, { st: '2', w: 100, hr: 133, vo2: 1.65 }, { st: '3', w: 150, hr: 158, vo2: 2.15 }];
const result = calculate(stages, 185);
assert(Math.abs(result.est - 2.69) < 1e-10, 'known linear test extrapolates correctly');
assert(result.checks.every(check => check.ok));
assert.equal(calculate(stages.map(stage => ({ ...stage, vo2: 1.5 })), 185).est, null, 'constant VO₂ must not produce Infinity or zero estimate');
assert.equal(calculate(stages, Infinity).est, null, 'infinite reference rejected');
assert.equal(calculate(stages, null).est, null, 'missing reference rejected');
assert.equal(calculate(stages, 1e9).est, null, 'out-of-range reference rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, hr: 110 })), 185).est, null, 'insufficient heart-rate span rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, w: 50 })), 185).est, null, 'duplicate workloads rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, vo2: 5 - stage.vo2 })), 185).est, null, 'falling oxygen uptake rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, hr: 230 - stage.hr })), 185).est, null, 'falling heart rate rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, hr: NaN })), 185).est, null, 'nonfinite sensor values rejected');
assert.equal(calculate(stages.map(stage => ({ ...stage, hr: null })), 185).est, null, 'missing sensor values rejected');
assert.equal(calculate([], 185).est, null, 'empty records do not produce an estimate');
assert.equal(calculate(stages.slice(0, 1), 185).est, null, 'single-stage estimates rejected');
const twoStages = calculate(stages.slice(0, 2), 185);
assert(Number.isFinite(twoStages.est), 'two valid stages remain supported');
assert(twoStages.checks.some(check => /fragile/.test(check.t)), 'two-stage limitation is visible');
const oneBad = calculate(stages.map((stage, i) => ({ ...stage, hr: i === 0 ? null : stage.hr })), 185);
assert(Number.isFinite(oneBad.est), 'remaining valid stages can produce an exploratory estimate');
assert(oneBad.checks.some(check => !check.ok), 'excluded stage is visibly flagged');
const flat = [{ st: '1', w: 50, hr: 110, vo2: 1 }, { st: '2', w: 100, hr: 120, vo2: 1.00001 }];
assert.equal(calculate(flat, 185).est, null, 'near-constant oxygen uptake cannot yield an unstable fit');
console.log('18 app calculator regression checks passed.');
